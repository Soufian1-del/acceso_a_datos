SET NAMES utf8mb4;
CREATE DATABASE IF NOT EXISTS ad_p13 CHARACTER SET utf8mb4 COLLATE utf8mb4_spanish_ci;
USE ad_p13;

DROP VIEW IF EXISTS v_receta_resumen;
DROP TABLE IF EXISTS valoracion;
DROP TABLE IF EXISTS receta_ingrediente;
DROP TABLE IF EXISTS receta;
DROP TABLE IF EXISTS ingrediente;
DROP TABLE IF EXISTS categoria;
DROP TABLE IF EXISTS usuario;

CREATE TABLE usuario (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nombre_usuario VARCHAR(30) NOT NULL UNIQUE,
    nombre VARCHAR(60) NOT NULL,
    ciudad VARCHAR(40) NULL COMMENT 'Barrio o ciudad; NULL si no la ha indicado',
    fecha_alta DATE NOT NULL
) COMMENT 'Personas registradas en la app';

CREATE TABLE categoria (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nombre VARCHAR(30) NOT NULL UNIQUE
) COMMENT 'Tipos de plato';

CREATE TABLE ingrediente (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nombre VARCHAR(40) NOT NULL UNIQUE,
    unidad VARCHAR(10) NOT NULL COMMENT 'g, ml, unidad o diente'
) COMMENT 'Ingredientes que se pueden usar en las recetas';

CREATE TABLE receta (
    id INT AUTO_INCREMENT PRIMARY KEY,
    titulo VARCHAR(80) NOT NULL,
    id_categoria INT NOT NULL,
    id_autor INT NOT NULL,
    minutos SMALLINT NOT NULL,
    raciones TINYINT NOT NULL DEFAULT 2,
    dificultad ENUM('facil', 'media', 'dificil') NOT NULL,
    calorias INT NULL COMMENT 'Por ración; NULL si no se ha calculado',
    vegetariana BOOLEAN NOT NULL DEFAULT FALSE,
    precio_aprox DECIMAL(5,2) NULL COMMENT 'Euros por ración',
    publicada DATE NOT NULL,
    instrucciones TEXT NOT NULL,
    CONSTRAINT fk_receta_categoria FOREIGN KEY (id_categoria) REFERENCES categoria (id),
    CONSTRAINT fk_receta_autor FOREIGN KEY (id_autor) REFERENCES usuario (id)
) COMMENT 'Recetas publicadas en la app';

CREATE TABLE receta_ingrediente (
    id_receta INT NOT NULL,
    id_ingrediente INT NOT NULL,
    cantidad DECIMAL(6,1) NOT NULL COMMENT 'En la unidad del ingrediente',
    PRIMARY KEY (id_receta, id_ingrediente),
    CONSTRAINT fk_ri_receta FOREIGN KEY (id_receta) REFERENCES receta (id),
    CONSTRAINT fk_ri_ingrediente FOREIGN KEY (id_ingrediente) REFERENCES ingrediente (id)
) COMMENT 'Qué ingredientes lleva cada receta y cuánto';

CREATE TABLE valoracion (
    id INT AUTO_INCREMENT PRIMARY KEY,
    id_receta INT NOT NULL,
    id_usuario INT NOT NULL,
    estrellas TINYINT NOT NULL COMMENT 'De 1 a 5',
    comentario VARCHAR(200) NULL,
    fecha DATE NOT NULL,
    UNIQUE (id_receta, id_usuario),
    CONSTRAINT fk_valoracion_receta FOREIGN KEY (id_receta) REFERENCES receta (id),
    CONSTRAINT fk_valoracion_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id)
) COMMENT 'Puntuaciones de los usuarios a las recetas';

CREATE VIEW v_receta_resumen AS
SELECT r.id, r.titulo, c.nombre AS categoria, u.nombre_usuario AS autor, r.minutos,
       ROUND(AVG(v.estrellas), 1) AS media_estrellas, COUNT(v.id) AS valoraciones
FROM receta r
JOIN categoria c ON c.id = r.id_categoria
JOIN usuario u ON u.id = r.id_autor
LEFT JOIN valoracion v ON v.id_receta = r.id
GROUP BY r.id, r.titulo, c.nombre, u.nombre_usuario, r.minutos;

