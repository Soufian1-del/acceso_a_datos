-- P12 · Consultas y objetos de resultado
-- Crea la base de datos ad_p12 con tres tablas: videojuego, empresa y version.
-- Se puede ejecutar todas las veces que haga falta: deja los datos como al principio.
-- Ejecútalo entero en DBeaver con Alt+X.

CREATE DATABASE IF NOT EXISTS ad_p12 CHARACTER SET utf8mb4 COLLATE utf8mb4_spanish_ci;
USE ad_p12;

DROP TABLE IF EXISTS version;
DROP TABLE IF EXISTS videojuego;
DROP TABLE IF EXISTS empresa;

-- Videojuegos. La puntuación es NULL en los juegos que no tienen nota.
CREATE TABLE videojuego (
    id            INT          NOT NULL AUTO_INCREMENT,
    titulo        VARCHAR(255) NOT NULL,
    max_jugadores INT          NOT NULL,
    puntuacion    DECIMAL(3,1) NULL,
    descripcion   VARCHAR(500) NULL,
    PRIMARY KEY (id)
);

-- Empresas que desarrollan o distribuyen juegos. anio_cierre es NULL si sigue abierta.
CREATE TABLE empresa (
    id             INT         NOT NULL AUTO_INCREMENT,
    nombre         VARCHAR(60) NOT NULL,
    pais           VARCHAR(40) NOT NULL,
    anio_fundacion INT         NULL,
    anio_cierre    INT         NULL,
    PRIMARY KEY (id)
);

-- Cada versión es un juego publicado en una plataforma.
-- id_distribuidor y titulo_alternativo pueden ser NULL.
CREATE TABLE version (
    id                 INT          NOT NULL AUTO_INCREMENT,
    id_videojuego      INT          NOT NULL,
    plataforma         VARCHAR(30)  NOT NULL,
    id_desarrollador   INT          NOT NULL,
    id_distribuidor    INT          NULL,
    lanzamiento        DATE         NOT NULL,
    titulo_alternativo VARCHAR(255) NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_version_videojuego FOREIGN KEY (id_videojuego) REFERENCES videojuego (id),
    CONSTRAINT fk_version_desarrollador FOREIGN KEY (id_desarrollador) REFERENCES empresa (id),
    CONSTRAINT fk_version_distribuidor FOREIGN KEY (id_distribuidor) REFERENCES empresa (id)
);

